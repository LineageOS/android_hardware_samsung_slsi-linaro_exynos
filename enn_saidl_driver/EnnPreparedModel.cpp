/**
 * @brief load input data on request and copy them to EnnBuffers for inputs
 * @details This function loads a buffers on request and copy them to EnnBuffers for inputs.
 *          EnnBuffers should be allocated before.
 *          If inputs[idx].hasNoValue==1, it loads 1)default values or 2)set size to 0.
 * @param[in] request Request
 * @returns return code
 */
int32_t EnnPreparedModel::loadInputData(const Request& request, BufferInfoOnExecute& bufInfoOnExecute) const {
    LOGD(ENN_DRIVER, "%s(+)\n", __func__);

    int32_t  *inputArray;
    int32_t   inputArrayIdx = 0;
    inputArray = new int32_t[model.main.operands.size()];
    for ( int32_t in = 0; in < model.main.operations.size(); in++) {
        const Operation&  androidOperation = model.main.operations[in];
        for (int32_t k = 0; k < androidOperation.inputs.size();k++) {
            auto inputId = androidOperation.inputs[k];
            if (model.main.operands[inputId].lifetime == Operand::LifeTime::SUBGRAPH_INPUT) {
                inputArray[inputArrayIdx++] = inputId;
            }
        }
    }

    const std::vector<Request::Argument>& inputs = request.inputs;
    LOGD(ENN_DRIVER, "No of input requests = %d\n", inputs.size());
    for (int32_t idx = 0; idx < inputs.size(); idx++) {
        int32_t it = idx;

        LOGD(ENN_DRIVER, "InputArray[%d]= %d\n", idx, inputArray[idx]);
        auto itr = find(model.main.inputIndexes.begin(), model.main.inputIndexes.end(), inputArray[idx]);
        if (itr != model.main.inputIndexes.end()) {
            it = itr - model.main.inputIndexes.begin();
        }
        const Request::Argument &inputArgs = inputs[it];

	if (inputArgs.lifetime == Request::Argument::LifeTime::NO_VALUE) {
            LOGD(ENN_DRIVER, "Input[%d] has no value\n", idx);
            EnnBufferPtr* ennBufferForInputs = reinterpret_cast<EnnBufferPtr *>(inputAddr);
            EnnBuffer *inputBufferAddr = ennBufferForInputs[idx];
            if (inputBufferAddr == nullptr) {
                LOGD(ENN_DRIVER, "Oops, inputBufferAddr is null!!, skip it!\n");
                continue;
            }
            auto &empty_buf = inputBufferAddr;
            reinterpret_cast<unsigned char *>(empty_buf->va)[0] = 0xFE;
            reinterpret_cast<unsigned char *>(empty_buf->va)[1] = 0xAB;
            LOGD(ENN_DRIVER, "Set Empty Input if length is 0\n");
            continue;
	}
        // Get virtual address of input data at #idx
        int32_t poolIndex = inputArgs.location.poolIndex;
        int32_t offset = inputArgs.location.offset;
        int32_t length = inputArgs.location.length;

        LOGD(ENN_DRIVER, "inputIndex= [%zu],it = [%d], poolIndex = [%d], offset = [%d], length = [%d]\n", idx, it, poolIndex, offset, length);
        if (const auto *sharedMem = std::get_if<SharedMemory>(&request.pools[poolIndex])) {
            char* virtAddr = nullptr;
            uint32_t msize;
            int32_t ret = bufInfoOnExecute.loadSharedMem(*sharedMem, true, virtAddr, msize);
            if (ret != RET_OK) {
                LOGE(ENN_DRIVER, "%s(-) Fail on getVirtualAddressOnPool!\n", __func__);
                delete[] inputArray;
                return ret;
            }

            ret = loadDataOnTargetBuffer(virtAddr + offset, length, idx);
            if (ret != RET_OK) {
                LOGE(ENN_DRIVER, "%s(-) Fail on loadDataOnTargetBuffer!\n", __func__);
                delete[] inputArray;
                return ret;
            }
        }
    }
    delete[] inputArray;
    LOGD(ENN_DRIVER, "%s(-)\n", __func__);
    return 0;
}

/**
 * @brief load data on a given srcAddr to matched target buffer which is given as an input index
 * @details This function loads data on a given srcAddr to matched target buffer which is given as an input index.
 * @param[in] srcAddr address for data to be loaded
 * @param[in] length length of data
 * @param[in] inputIdx input index on request.inputs
 * @returns return code
 */
int32_t EnnPreparedModel::loadDataOnTargetBuffer(char* srcAddr, int32_t length, int32_t inputIdx) const {
    LOGD(ENN_DRIVER, "%s(+)\n", __func__);

    void* targetAddr = nullptr;
    int32_t targetSize = 0;

    // Get android operand id used as model input
    int32_t androidOperandIdx = model.main.inputIndexes[inputIdx];

    // Which operation uses this operand id as input?


     // To be loaded on input buffers
     // @todo Currently, input buffer order and input indexes has same order.
    EnnBufferPtr* ennBufferForInputs = reinterpret_cast<EnnBufferPtr *>(inputAddr);
    EnnBuffer *inputBufferAddr = ennBufferForInputs[inputIdx];
    if (inputBufferAddr == nullptr) {
        LOGD(ENN_DRIVER, "Oops, inputBufferAddr is null!!, skip it!\n");
        return RET_OK;
    }
    LOGD(ENN_DRIVER, "inputBufferAddr addr:%p, size=%d\n", inputBufferAddr->va, inputBufferAddr->size);
    targetAddr = inputBufferAddr->va;
    targetSize = inputBufferAddr->size;

    if (targetAddr == nullptr) {
        LOGD(ENN_DRIVER, "Oops, targetAddr == nullptr, skip it!\n");
    } else if (targetSize == 0) {
        LOGD(ENN_DRIVER, "Oops, targetSize == 0, skip it!\n");
    } else if (targetSize != length) {
        LOGD(ENN_DRIVER, "Oops, Source and TargetSize not matching!!\n");
    } else {
        LOGD(ENN_DRIVER, "Load from %p to %p, size=%d\n", reinterpret_cast<void*>(srcAddr), targetAddr, length);
        std::memcpy(targetAddr, reinterpret_cast<const void*>(srcAddr), length);
    }
#ifdef NNDRIVER_DEBUG
    //For Debug
    LOGD(ENN_DRIVER, "Dump addr=[%p], size=[%d] on stdio...\n", targetAddr, targetSize);
    unsigned char* chPtr = reinterpret_cast<unsigned char*>(targetAddr);
    for (int32_t pidx = 0; pidx < targetSize; pidx++) {
        LOGD(ENN_DRIVER, "%x \n", static_cast<int32_t>(chPtr[pidx]));
    }
    LOGD(ENN_DRIVER, "Dump addr=[%p], size=[%d] on stdio...Done!\n", targetAddr, length);
#endif
    LOGD(ENN_DRIVER, "%s(-)\n", __func__);
    return RET_OK;
}

