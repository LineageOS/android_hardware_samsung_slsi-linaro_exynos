GeneralResult<std::pair<SyncFence, ExecuteFencedInfoCallback>> EnnPreparedModel::executeFenced(const Request& request,
                                              const std::vector<SyncFence>& waitFor,
                                              MeasureTiming measure,
                                              const OptionalTimePoint& /*deadline*/,
                                              const OptionalDuration& /*loopTimeoutDuration*/,
                                              const OptionalDuration& /*duration*/,
					      const std::vector<nn::TokenValuePair>& hints,
                                              const std::vector<nn::ExtensionNameAndPrefix>& extensionNameToPrefix) const {
    LOGD(ENN_DRIVER, "%s(+)\n", __func__);

    std::chrono::steady_clock::time_point driverStart, driverEnd, deviceStart, deviceEnd, driverStartAfterFence;
    if (measure == MeasureTiming::YES) driverStart = std::chrono::steady_clock::now();

    const auto result = validateRequestForModel(request, this->model);
    if (!result.ok()) {
       return NN_ERROR( ErrorStatus::INVALID_ARGUMENT);
    }
    if(!verifyDimension(request, this->model)) {
       return NN_ERROR( ErrorStatus::INVALID_ARGUMENT);
    }
    // Wait for the dependent events to signal
    for (const auto& syncFence : waitFor) {
       if (!syncFence.getSharedHandle()) {
           return NN_ERROR(ErrorStatus::INVALID_ARGUMENT);
        }

        if (syncFence.syncWait({}) != SyncFence::FenceState::SIGNALED) {
            return NN_ERROR(ErrorStatus::GENERAL_FAILURE) << "syncWait failed";
        }
    }

    if (measure == MeasureTiming::YES) driverStartAfterFence = std::chrono::steady_clock::now();
    // Execute
    std::vector<OutputShape> outputshape;
    Timing timing;

    if (measure == MeasureTiming::YES) deviceStart = std::chrono::steady_clock::now();
    //Removing timimg from execute call and mesure outside. Nihar ?
    int32_t ret = nnAgent_->executeSynchronously(this,request,measure,outputshape,timing);
    if (ret != RET_OK) {
       if (ret == INVALID_PARAMS) {
          return NN_ERROR(ErrorStatus::INVALID_ARGUMENT);
       }
      return NN_ERROR(ErrorStatus::GENERAL_FAILURE);
    }
    if (measure == MeasureTiming::YES) deviceEnd = std::chrono::steady_clock::now();

    Timing timingSinceLaunch = {};
    Timing timingAfterFence = {};
    if (measure == MeasureTiming::YES) {
        driverEnd = std::chrono::steady_clock::now();
        timingSinceLaunch = {.timeOnDevice = deviceEnd - deviceStart,
                             .timeInDriver = driverEnd - driverStart};
        timingAfterFence = {.timeOnDevice = deviceEnd - deviceStart,
                            .timeInDriver = driverEnd - driverStartAfterFence};
    }

#if 0
    //Nihar : check if this is needed for Memory Domain
    for (const auto& output : request.outputs) {
        const uint32_t poolIndex = output.location.poolIndex;
	const auto& pool = request.pools[poolIndex];
	if(std::holds_alternative<Request::MemoryDomainToken>(pool)) {
	    bufferWrappers[poolIndex]->setInitialized(true);
	}
     }
#endif
    ExecuteFencedInfoCallback fencedExecutionCallback = [timingSinceLaunch, timingAfterFence]() {
        return std::make_pair(timingSinceLaunch, timingAfterFence);
    };

    LOGD(ENN_DRIVER, "%s(-)\n", __func__);
    return std::make_pair(SyncFence::createAsSignaled(), std::move(fencedExecutionCallback));
}

