static const V1_2::Timing kNoTiming = {.timeOnDevice = UINT64_MAX, .timeInDriver = UINT64_MAX};

class DriverExecutionCallback_1_2 : public V1_2::IExecutionCallback {
 public:
    DriverExecutionCallback_1_2(executeSynchronously_cb cb) : myCb(cb) {
    }

    Return<void> notify(V1_0::ErrorStatus /*status*/) {
        return Void();
    }

    Return<void> notify_1_2(V1_0::ErrorStatus status, const hidl_vec<V1_2::OutputShape>& outputShapes, const V1_2::Timing& timing) {
        myCb(status, outputShapes, timing);
        return Void();
    }

    executeSynchronously_cb myCb;
};

