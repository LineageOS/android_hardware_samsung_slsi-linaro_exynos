bool EdenPreparedModel::IsInvalidParams() {

    for (const V1_3::Operation &operation : model.main.operations) {
        int32_t opType = static_cast<int32_t>(operation.type);
        // Check if first dimension of input0 is not 1 for depthwise_conv2D
        if (opType == ANEURALNETWORKS_DEPTHWISE_CONV_2D &&
                    (model.main.operands[operation.inputs[1]].dimensions[0] != 1)) {
            return true;
        }

        if (opType == ANEURALNETWORKS_STRIDED_SLICE) {
            const uint32_t axis_mask_offset = model.main.operands[operation.inputs[6]].location.offset;
            const int32_t *axis_mask = (int32_t*)(model.operandValues.data() + axis_mask_offset);

            const uint32_t begin_offset = model.main.operands[operation.inputs[1]].location.offset;
            const int32_t *begin  = (int32_t*)(model.operandValues.data() + begin_offset);

            const uint32_t end_offset = model.main.operands[operation.inputs[2]].location.offset;
            const int32_t *end  = (int32_t*)(model.operandValues.data() + end_offset);

            const uint32_t strides_offset = model.main.operands[operation.inputs[3]].location.offset;
            const int32_t *strides  = (int32_t*)(model.operandValues.data() + strides_offset);

            uint32_t outputDim = (end[0] - begin[0])/strides[0];

            // This is hack to pass VTS tests.If shrink_axis_mask is not zero, then no negative strides
            // are allowed and output dimensions should be 1.
            if (axis_mask[0] && ((strides[0] < 0) || (outputDim != 1))) {
                return  true;
            }
        }
    }
    return false;
}
